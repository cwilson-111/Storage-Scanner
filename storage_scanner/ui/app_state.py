"""What the main window's parts share: the attributes and methods one
module of StorageScannerApp uses from another.

StorageScannerApp (storage_scanner/app.py) is built from the mixins under
storage_scanner/ui/, and the windows it opens (DuplicatesWindow,
GrowthHistoryWindow, CleanupWindow, FileListWindow, TreemapPane) are handed
the app itself. An attribute set in one file and read in another, or a
method called across files, is declared here once, so mypy checks every use
of it: a misspelled name or a wrong argument count is a type error instead
of an AttributeError the first time that code path runs.

- A window's `app` parameter is annotated `AppState`.
- Every mixin derives from `AppMixin`: AppState while type checking, plain
  `object` at run time, so the declarations cost nothing when the app runs.
  AppState itself exists only while type checking (import it under
  `if TYPE_CHECKING:`).

AppState is a plain class, not a typing.Protocol, on purpose: a Protocol's
bare `name: type` members are abstract, and mypy lets each subclass's first
`self.name = value` redeclare them with the value's narrower type, so
`self.scan_thread = None` in one mixin and a Thread in another would leave
each file with its own, conflicting, idea of the attribute.

pyproject.toml has mypy check the bodies of the untyped functions under
storage_scanner/ui/ and app.py (check_untyped_defs), which is where every
one of these uses is.
"""

